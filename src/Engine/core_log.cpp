#include "stdafx.h"
#include "core_log.h"
//=============================================================================
namespace app
{
	void Exit();
}
//=============================================================================
void core::Print(const std::string& msg)
{
	puts(msg.c_str());
}
//=============================================================================
void core::Info(const std::string& msg)
{
	Print("\033[32m[INFO]:\033[0m " + msg);
}
//=============================================================================
void core::Warning(const std::string& msg)
{
	Print("\033[33m[WARNING]:\033[0m " + msg);
}
//=============================================================================
void core::Debug(const std::string& msg)
{
#if defined(_DEBUG)
	Print("\033[36m[DEBUG]:\033[0m " + msg);
#endif
}
//=============================================================================
void core::Error(const std::string& msg)
{
	Print("\033[31m[ERROR]:\033[0m " + msg);
}
//=============================================================================
void core::Fatal(const std::string& msg)
{
	app::Exit();
	Print("\033[35m[FATAL]:\033[0m " + msg);
}
//=============================================================================